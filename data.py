"""
SAMPLE campus dataset - the single source of truth for the built-in demo.

    ***  THIS IS A MADE-UP CAMPUS. IT IS NOT A REAL PLACE.  ***

No campus map is supplied with DSA Task 1 of the GDG-USAR brief - unlike the
other tasks, it says only "Represent locations and connections as a graph".
So the graph is ours to define, and this file defines a deliberately small
SYNTHETIC one: 14 plausible-sounding buildings on a 285 m x 330 m grid. The
building names are generic on purpose. Nothing here was surveyed, measured or
copied from any real institution, and the numbers are not real walking
distances.

Its job is to be verifiable by hand and to make BFS and Dijkstra visibly
disagree, which is what the task actually assesses.

    To use your own campus, do NOT edit this file. Write a JSON campus
    file instead (see campuses/MY-CAMPUS.template.json) and pass it:

        python main.py route --campus campuses/my-campus.json \
                             --from library --to hostel

Everything downstream (the CLI, the SVG map, the interactive HTML demo, the
benchmarks and the tests) is generated from the two tables in this module.
Adding a location or a pathway here updates all of them at once.

Coordinate system
-----------------
(x, y) are metres on a flat campus grid. `y` grows southwards, which matches
how the map is drawn on screen (SVG already has y growing downwards).
The coordinates are what make an A* heuristic possible: straight-line
distance between two points is a lower bound on the walking distance.

Edge weights
------------
Most pathway lengths are DERIVED from the coordinates
(round(euclidean / 5) * 5 metres) so the map and the graph can never
disagree. A few pathways carry an explicit `OVERRIDE` weight because the
real walk is longer than the straight line - service roads, buildings in
the way, and so on. Every override is documented below.
"""

