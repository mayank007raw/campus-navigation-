# --------------------------------------------------------------------------
# Explicit weights, in metres, for pathways where the real walk is longer
# than the straight line between the two buildings. Every entry here is
# >= the euclidean distance, which keeps the A* heuristic admissible.
# --------------------------------------------------------------------------
OVERRIDES: dict[frozenset[str], int] = {
    frozenset({"sports", "library"}): 420,
    #   straight line is 245 m, but the only route is the perimeter service
    #   road around the sports field. This made-up detour is what makes BFS
    #   take a 420 m route while Dijkstra finds a 270 m one - the little
    #   teaching example the whole project is built around.
    frozenset({"hostel_m", "block_c"}): 260,
    #   straight line is 135 m, but the sports field is in the way.
}

#: Why each hand-set weight differs from the map distance, carried through to
#: the JSON export and to DECISIONS.md.
WEIGHT_NOTES: dict[frozenset[str], str] = {
    frozenset({"sports", "library"}):
        "perimeter service road around the sports field",
    frozenset({"hostel_m", "block_c"}):
        "sports field is directly in the way",
}

ROUNDING_STEP = geo.DEFAULT_ROUNDING_STEP

CAMPUS_LABEL = "Sample Campus (synthetic)"
CAMPUS_NOTE = ("Illustrative dataset created for this task. The locations and "
               "distances are invented, not surveyed.")


def euclidean(a: str, b: str) -> float:
    """Straight-line distance in metres between two locations' coordinates."""
    _, _, ax, ay = LOCATIONS[a]
    _, _, bx, by = LOCATIONS[b]
    return geo.euclidean(ax, ay, bx, by)


def derived_weight(a: str, b: str) -> int:
    """Walking distance used when no explicit override exists."""
    return geo.derive_weight(*coordinates(a), *coordinates(b), ROUNDING_STEP)


def edges() -> list[tuple[str, str, int, str]]:
    """Return the pathway list as (a, b, weight_metres, kind) tuples."""
    out: list[tuple[str, str, int, str]] = []
    for a, b, kind in PATHS:
        w = OVERRIDES.get(frozenset({a, b}), derived_weight(a, b))
        out.append((a, b, w, kind))
    return out


def coordinates(node: str) -> tuple[float, float]:
    _, _, x, y = LOCATIONS[node]
    return x, y


def display_name(node: str) -> str:
    return LOCATIONS[node][0]


def category(node: str) -> str:
    return LOCATIONS[node][1]


